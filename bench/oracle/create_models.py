import basico
import os

output_dir = "bench/models"
os.makedirs(output_dir, exist_ok=True)

def set_initial_concentrations_to_zero():
    species_df = basico.get_species()
    for name in species_df.index:
        basico.set_species(name, initial_concentration=0.0)

def create_m1():
    basico.new_model(name="M1")
    basico.add_compartment("compartment", initial_size=1.0)
    basico.add_reaction("R1", scheme="S + cat -> catS", rate_law="Mass action (irreversible)")
    basico.add_reaction("R2", scheme="catS -> S + cat", rate_law="Mass action (irreversible)")
    basico.add_reaction("R3", scheme="catS -> P + cat", rate_law="Mass action (irreversible)")
    basico.add_reaction("R4", scheme="P + cat -> catS", rate_law="Mass action (irreversible)")
    set_initial_concentrations_to_zero()
    file_path = os.path.join(output_dir, "M1.cps")
    basico.save_model(file_path, overwrite=True)
    print(f"Saved model M1 to {file_path}")

