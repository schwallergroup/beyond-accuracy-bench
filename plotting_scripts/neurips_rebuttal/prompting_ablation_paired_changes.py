"""Regenerate Figure 5's paired effects from released judgments and task results.

Uses the historical standard iteration-3 judging pass. Same-model judges are
excluded before averaging ratings. Confidence intervals bootstrap paired
system differences (4,000 resamples, seed 0). Accuracy uses the paired table
generated by paired_prompt_effects.py. Regenerated layout may differ slightly
from the final manuscript's exported artwork.
"""
from pathlib import Path
import argparse
import sys
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from plotting_scripts.neurips_rebuttal.step_instruction_standard_vs_step_scatter import (
    _trace_scores, STANDARD_JUDGE_INPUTS, STEP_JUDGE_INPUTS,
)
from plotting_scripts.neurips.paper_model_metadata import LABELS, MODEL_COLORS, DISPLAY_LABELS
from plotting_scripts.styling import apply_paper_rcparams


def build_data(accuracy_path):
    standard = _trace_scores(STANDARD_JUDGE_INPUTS, r"\s+with\s+mechanism\s+info$")
    step = _trace_scores(STEP_JUDGE_INPUTS, r"\s+step\s+instruction$")
    paired = standard.merge(step, on=["model", "sample_id", "rubric_key"],
                            suffixes=("_standard", "_step"), validate="one_to_one")
    rows = []
    for (model, rubric), group in paired.groupby(["model", "rubric_key"]):
        if rubric not in ["predictive_sharpness", "feature_to_action_faithfulness"]:
            continue
        delta = (group.score_step - group.score_standard).to_numpy()
        rng = np.random.default_rng(0)
        means = delta[rng.integers(0, len(delta), (4000, len(delta)))].mean(axis=1)
        lo, hi = np.percentile(means, [2.5, 97.5])
        rows.append(dict(model=model, metric=rubric, n_paired=len(delta),
                         paired_change=delta.mean(), change_ci_low=lo, change_ci_high=hi))
    accuracy = pd.read_csv(accuracy_path)
    accuracy = accuracy.loc[accuracy.metric == "Accuracy", list(rows[0])].copy()
    for column in ["paired_change", "change_ci_low", "change_ci_high"]:
        accuracy[column] *= 100
    return pd.concat([pd.DataFrame(rows), accuracy], ignore_index=True)


def plot(data, output):
    apply_paper_rcparams()
    order = [label.removesuffix(" with Mechanism Info") for label in LABELS
             if label.removesuffix(" with Mechanism Info") in set(data.model)]
    metrics = [("predictive_sharpness", "(a) Predictive Reasoning", r"$\Delta$ PR score (Iteration 3)"),
               ("feature_to_action_faithfulness", "(b) Discriminative Experiment Design", r"$\Delta$ DED score (Iteration 3)"),
               ("Accuracy", "(c) Identification Accuracy", r"$\Delta$ Accuracy (Iteration 5, pp)")]
    fig, axes = plt.subplots(1, 3, figsize=(10.5, 4.3), sharey=True)
    for ax, (metric, title, xlabel) in zip(axes, metrics):
        panel = data[data.metric == metric].set_index("model").loc[order]
        for y, (model, row) in enumerate(panel.iterrows()):
            ax.errorbar(row.paired_change, y,
                        xerr=[[row.paired_change-row.change_ci_low], [row.change_ci_high-row.paired_change]],
                        fmt="o", color=MODEL_COLORS[f"{model} with Mechanism Info"],
                        markersize=4, elinewidth=1, capsize=2)
        ax.axvline(0, color="0.4", linestyle="--", linewidth=.8)
        ax.set_title(title, fontsize=10)
        ax.set_xlabel(xlabel)
        ax.grid(axis="y", alpha=.15)
        ax.spines[["top", "right"]].set_visible(False)
    axes[0].set_yticks(range(len(order)), [DISPLAY_LABELS[f"{m} with Mechanism Info"] for m in order])
    axes[0].invert_yaxis()
    fig.tight_layout()
    fig.savefig(output, dpi=600, bbox_inches="tight")
    plt.close(fig)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=Path(__file__).parent / "step_instruction_judge_analysis")
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    data = build_data(Path(__file__).parent / "step_instruction_judge_analysis/nine_model_paired_prompt_effects.csv")
    data.to_csv(args.output_dir / "prompting_ablation_paired_changes.csv", index=False)
    plot(data, args.output_dir / "prompting_ablation_paired_changes.png")
    print(data.to_string(index=False))
